int Pattern(int frame, int x, int y)
{
  const int v = (x * 37 + y * 91 + frame * 53) % 256;
  return (x + y + frame) % 3 == 0 ? 255 - v : v;
}

void Put32(std::string& image, std::size_t at, std::uint32_t value)
{
  for (int i = 0; i < 4; ++i)
  {
    image[at + i] = static_cast<char>(value >> (8 * i));
    image[at + 4 + (3 - i)] = static_cast<char>(value >> (8 * i));  // and big endian after
  }
}

// One directory record.
std::string Record(const std::string& name, std::uint32_t extent, std::uint32_t length,
                   bool folder)
{
  std::string record(33 + name.size() + (name.size() + 1) % 2, '\0');
  record[0] = static_cast<char>(record.size());
  Put32(record, 2, extent);
  Put32(record, 10, length);
  record[25] = folder ? 2 : 0;
  record[32] = static_cast<char>(name.size());
  std::memcpy(record.data() + 33, name.data(), name.size());
  return record;
}

// A .cvm-like image: a 6144-byte header, then an ISO with a file in the root
// and one in a folder.
std::string MakeImage()
{
  const std::string header_size(6144, '\0');
  std::string iso(26 * SECTOR, '\0');
  // Primary volume descriptor at sector 16, the end of the set at 17.
  iso[16 * SECTOR] = 1;
  std::memcpy(iso.data() + 16 * SECTOR + 1, "CD001", 5);
  iso[16 * SECTOR + 128] = 0x00;
  iso[16 * SECTOR + 129] = 0x08;  // 2048-byte blocks
  const std::string root = Record(std::string(1, '\0'), 18, SECTOR, true);
  std::memcpy(iso.data() + 16 * SECTOR + 156, root.data(), root.size());
  iso[17 * SECTOR] = static_cast<char>(255);
  std::memcpy(iso.data() + 17 * SECTOR + 1, "CD001", 5);
  // The root (sector 18): itself, its parent, a file and a folder.
  std::string records = Record(std::string(1, '\0'), 18, SECTOR, true) +
                        Record(std::string(1, '\1'), 18, SECTOR, true) +
                        Record("SEGA_E.SFD;1", 20, 3000, false) + Record("MOVIES", 19, SECTOR, true);
  std::memcpy(iso.data() + 18 * SECTOR, records.data(), records.size());
  // The folder (sector 19).
  records = Record(std::string(1, '\0'), 19, SECTOR, true) +
            Record(std::string(1, '\1'), 18, SECTOR, true) + Record("OPENING.SFD;1", 22, 5000, false);
  std::memcpy(iso.data() + 19 * SECTOR, records.data(), records.size());
  std::string image = std::string("CVMH") + header_size.substr(4) + iso;
  image[6144 + 22 * SECTOR] = 'O';
  return image;
}
