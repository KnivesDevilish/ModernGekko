int main()
{
  const std::string image = MakeImage();
  {
    std::istringstream in(image);
    const auto opening = FindInIso(in, "opening.sfd");
    if (!opening || opening->first != 6144 + 22 * SECTOR || opening->second != 5000 ||
        image[opening->first] != 'O')
      return 1;
    const auto sega = FindInIso(in, "SEGA_E.SFD");
    if (!sega || sega->first != 6144 + 20 * SECTOR || sega->second != 3000)
      return 2;
    if (FindInIso(in, "ENDING.SFD") || FindInIso(in, "MOVIES"))
      return 3;
    std::istringstream not_iso(std::string(64 * 1024, 'x'));
    if (FindInIso(not_iso, "OPENING.SFD"))
      return 4;
  }

  const std::filesystem::path root =
      std::filesystem::temp_directory_path() / "moderngekko_preview_video_test";
  std::filesystem::remove_all(root);
  std::filesystem::create_directories(root / "files");
  std::ofstream(root / "files" / "Image3.cvm", std::ios::binary) << image;
  std::ofstream(root / "files" / "TITLE_G.SFD", std::ios::binary) << "not a video at all";
  const auto inside = FindVideoSource(root, "files/Image3.cvm:OPENING.SFD");
  const auto whole = FindVideoSource(root, "files/TITLE_G.SFD");
  if (!inside || inside->file != root / "files" / "Image3.cvm" ||
      inside->offset != 6144 + 22 * SECTOR || inside->length != 5000 || !whole ||
      whole->offset != 0 || whole->length != 18)
    return 5;
  if (FindVideoSource(root, "files/OPENING.SFD") ||
      FindVideoSource(root, "files/Image3.cvm:ENDING.SFD") ||
      FindVideoSource(root, "files/Image1.cvm:OPENING.SFD"))
    return 6;

  // Neither of these is a video: each fails, soon.
  for (const VideoSource& source : {*whole, *inside})
  {
    PreviewVideo video;
    video.Start(source, {{0, 10}, {200, 300}});
    const auto give_up = std::chrono::steady_clock::now() + std::chrono::seconds(10);
    while (!video.Failed() && !video.Ready() && std::chrono::steady_clock::now() < give_up)
      std::this_thread::sleep_for(std::chrono::milliseconds(5));
    std::vector<std::uint8_t> rgba;
    if (!video.Failed() || video.Ready() || video.Take(100, rgba))
      return 7;
    video.Stop();
    if (video.Failed() || video.Running())
      return 8;
  }

  // The games' kind of video, decoded to the exact grey of each block.
  std::ofstream(root / "files" / "TINY.SFD", std::ios::binary)
      .write(reinterpret_cast<const char*>(TMPGEXS_VIDEO), sizeof(TMPGEXS_VIDEO));
  const auto tiny = FindVideoSource(root, "files/TINY.SFD");
  if (!tiny)
    return 9;
  {
    PreviewVideo video;
    video.Start(*tiny, {{0, 1}});
    std::vector<std::uint8_t> rgba;
    for (int frame = 0; frame < 2; ++frame)
    {
      const auto give_up = std::chrono::steady_clock::now() + std::chrono::seconds(10);
      while (!video.Take(frame, rgba) && std::chrono::steady_clock::now() < give_up)
        std::this_thread::sleep_for(std::chrono::milliseconds(2));
      if (video.Width() != 64 || video.Height() != 48 || rgba.size() != 64 * 48 * 4)
        return 10;
      for (int by = 0; by < 6; ++by)
      {
        for (int bx = 0; bx < 8; ++bx)
        {
          const int luma = Pattern(frame, bx, by);
          const int grey = std::clamp(((luma - 16) * 76309) >> 16, 0, 255);  // pl_mpeg's
          const std::uint8_t* pixel = rgba.data() + ((by * 8 + 4) * 64 + bx * 8 + 4) * 4;
          if (pixel[0] != grey || pixel[1] != grey || pixel[2] != grey)
          {
            std::printf("frame %d block %d,%d: %d, not %d\n", frame, bx, by, pixel[0], grey);
            return 11;
          }
        }
      }
    }
  }
  std::filesystem::remove_all(root);

  std::puts("launcher preview video: ok");
  return 0;
}
